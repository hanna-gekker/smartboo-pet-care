// Step 2 of `npm run tokens`: tokens.json → src/styles/tokens.css with Style Dictionary.
//
// - Primitives and layout tokens go to :root.
// - Light colors go to :root; Dark colors go to [data-theme="dark"] and also follow the phone
//   (prefers-color-scheme) unless the app forces the light theme with [data-theme="light"].
// - CSS names are the Figma names: surface/canvas → --surface-canvas, blue/700 → --blue-700.
// - Semantic colors keep pointing to primitives: --accent-primary: var(--blue-700).

import StyleDictionary from 'style-dictionary'

const MODES = { light: 'Light', dark: 'Dark' }

// "SF Pro" isn't a name browsers can load; the system font stack is SF Pro on Apple devices.
const FONT_STACKS = {
  'SF Pro': '-apple-system, BlinkMacSystemFont, "SF Pro Text", "SF Pro Display", system-ui, sans-serif',
}

const isMode = (token) => Object.values(MODES).includes(token.path[0])
const cssName = (path) => `--${path.join('-')}`
const nameOf = (token) => cssName(isMode(token) ? token.path.slice(1) : token.path)

const valueOf = (token) => {
  const original = token.original.$value
  if (typeof original === 'string' && original.includes('{')) {
    return original.replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref.split('.'))})`)
  }
  if (token.$type === 'fontFamily') return FONT_STACKS[original] ?? original
  return String(original)
}

const line = (token) => {
  const note = token.$description ? ` /* ${token.$description} */` : ''
  return `  ${nameOf(token)}: ${valueOf(token)};${note}`
}

// Light and Dark intentionally share names, so Style Dictionary's own clash warning is off
// and this check runs instead: within one theme, every CSS name must be unique.
const checkUnique = (tokens) => {
  const seen = new Set()
  for (const t of tokens) {
    const name = nameOf(t)
    if (seen.has(name)) throw new Error(`Two tokens would both become ${name}. Rename one in Figma.`)
    seen.add(name)
  }
}

StyleDictionary.registerTransform({
  name: 'name/smartboo',
  type: 'name',
  transform: (token) => nameOf(token).slice(2),
})

StyleDictionary.registerFormat({
  name: 'css/smartboo',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens
    const shared = all.filter((t) => !isMode(t))
    const primitives = shared.filter((t) => t.$type === 'color')
    const layout = shared.filter((t) => t.$type !== 'color')
    const light = all.filter((t) => t.path[0] === MODES.light)
    const dark = all.filter((t) => t.path[0] === MODES.dark)
    checkUnique([...shared, ...light])
    checkUnique([...shared, ...dark])
    const block = (tokens) => tokens.map(line).join('\n')

    return `/*
 * Generated by \`npm run tokens\` from tokens.json (Figma Variables). Do not edit by hand.
 * To update: replace design/figma-variables.json with a new export, then run \`npm run tokens\`.
 */

:root {
  /* Primitives */
${block(primitives)}

  /* Layout */
${block(layout)}

  /* Colors — light */
${block(light)}
}

/* Colors — dark, following the phone */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(dark).replace(/^/gm, '  ')}
  }
}

/* Colors — dark, chosen in the app */
[data-theme="dark"] {
${block(dark)}
}
`
  },
})

const sd = new StyleDictionary({
  source: ['tokens.json'],
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'disabled' },
  platforms: {
    css: {
      transforms: ['name/smartboo'],
      buildPath: 'src/styles/',
      files: [{ destination: 'tokens.css', format: 'css/smartboo' }],
    },
  },
})

await sd.buildAllPlatforms()
console.log('✓ src/styles/tokens.css from tokens.json')
